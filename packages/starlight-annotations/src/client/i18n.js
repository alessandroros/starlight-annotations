export const builtIn = { en, it, de, fr, es };

export function strings(lang = 'en', overrides = {}) {
  const tag = String(lang || 'en').toLowerCase();
  const base = tag.split('-')[0];
  // English is the fallback for any string a language does not define.
  return {
    ...en,
    ...(overrides.en ?? {}),
    ...(builtIn[base] ?? {}),
    ...(overrides[base] ?? {}),
    ...(overrides[tag] ?? {}),
  };
}
